"""Literature-derived void-star expectations, independent of engine tables.

See references/VOID_STARS_REVIEW.md for the classical pair tables and the
Zhongzhou primary/secondary convention. All birth inputs are fictional.
"""

import pytest

from astrbot_plugin_ziwei.calendar_core import BirthInput
from astrbot_plugin_ziwei.commands import parse_request
from astrbot_plugin_ziwei.engine import build_chart
from astrbot_plugin_ziwei.rules import RuleProfile

# Ordered as (primary, secondary), from the five stem-group pairs followed
# by matching the birth stem's yin/yang to the palace branch's yin/yang.
JIE_BY_STEM = {
    "甲": ("申", "酉"),
    "乙": ("未", "午"),
    "丙": ("辰", "巳"),
    "丁": ("卯", "寅"),
    "戊": ("子", "丑"),
    "己": ("酉", "申"),
    "庚": ("午", "未"),
    "辛": ("巳", "辰"),
    "壬": ("寅", "卯"),
    "癸": ("丑", "子"),
}

# The six ten-year cycles start at 甲子、甲戌、甲申、甲午、甲辰、甲寅.
# This table is transcribed from the literature, not generated by wrap().
XUN_PAIRS = (
    ("戌", "亥"),
    ("申", "酉"),
    ("午", "未"),
    ("辰", "巳"),
    ("寅", "卯"),
    ("子", "丑"),
)


def void_pair(chart, sid):
    stars = sorted(
        (star for star in chart["stars"] if star["id"] == sid),
        key=lambda star: star["secondary"],
    )
    assert len(stars) == 2
    primary, secondary = stars
    assert primary["secondary"] is False and secondary["secondary"] is True
    assert primary["instance_id"] != secondary["instance_id"]
    for star in stars:
        assert 1 <= star["branch"] <= 12
        assert star in chart["palaces"][star["branch"] - 1]["stars"]
    return tuple("子丑寅卯辰巳午未申酉戌亥"[star["branch"] - 1] for star in stars)


@pytest.mark.parametrize("offset", range(60), ids=lambda offset: str(1984 + offset))
def test_all_sixty_years_match_literature_pairs_and_primary_secondary(offset):
    stem = "甲乙丙丁戊己庚辛壬癸"[offset % 10]
    chart = build_chart(
        BirthInput(1984 + offset, 6, 15, 12, 0, "男", true_solar=False),
        RuleProfile(void_rule=2),
    )
    assert chart["normalized"]["year_stem"] == offset % 10 + 1
    assert chart["normalized"]["year_branch"] == offset % 12 + 1
    assert void_pair(chart, 77) == JIE_BY_STEM[stem]
    yang, yin = XUN_PAIRS[offset // 10]
    assert void_pair(chart, 78) == (
        (yang, yin) if stem in "甲丙戊庚壬" else (yin, yang)
    )
    assert {s["id"] for s in chart["stars"] if s["secondary"]} == {77, 78}


@pytest.mark.parametrize(
    "text,boundary,jie,xun",
    [
        ("2024-02-03 12:00 女", "next_day", ("丑", "子"), ("巳", "辰")),
        ("2024-02-06 12:00 女", "next_day", ("丑", "子"), ("巳", "辰")),
        ("2024-02-09 23:30 女", "next_day", ("申", "酉"), ("寅", "卯")),
        ("2024-02-09 23:30 女", "midnight", ("丑", "子"), ("巳", "辰")),
        ("2024-02-10 00:30 女", "midnight", ("申", "酉"), ("寅", "卯")),
    ],
)
def test_voids_use_astrology_lunar_year_and_respect_late_zi_boundary(
    text, boundary, jie, xun
):
    # 立春 alone must not switch 癸卯 to 甲辰 for these natal star positions.
    request = parse_request(text + " 真太阳时=关")
    chart = build_chart(request.birth, RuleProfile(void_rule=2, late_zi_rule=boundary))
    assert void_pair(chart, 77) == jie
    assert void_pair(chart, 78) == xun
